type Frame = { cy: number; sy: number; buffer: Float32Array; chars: string[] };

type Point = [number, number, number, number, number, number];
const cols = 160,
  rows = 64;
const mask = maskText.trimEnd().split('\n');
const ramp = '.:;=+*#%@';
const solid = (x: number, y: number) => /[@#]/.test(mask[y]?.[x] ?? ' ');

function addCell(points: Point[], x: number, y: number) {
  for (const dy of [0, 0.5]) {
    for (const dx of [0, 0.5]) {
      for (const z of [-0.5, 0.5]) points.push([x + dx - 80, (y + dy - mask.length / 2) * 2, z, 0, 0, z * 2]);
    }
  }
  for (const [nx, ny] of [
    [-1, 0],
    [1, 0],
    [0, -1],
    [0, 1]
  ]) {
    if (solid(x + nx, y + ny)) continue;
    for (let z = -0.5; z <= 0.501; z += 1 / 24) {
      points.push([x + 0.5 + nx * 0.5 - 80, (y + 0.5 + ny * 0.5 - mask.length / 2) * 2, z, nx, ny, 0]);
    }
  }
}

function createPoints() {
  const points: Point[] = [];
  for (let y = 0; y < mask.length; y++) {
    for (let x = 0; x < cols; x++) {
      if (solid(x, y)) addCell(points, x, y);
    }
  }
  return points;
}

function projectPoint(point: Point, frame: Frame) {
  const { cy, sy, buffer, chars } = frame;
  const [x, y, z] = point;
  const cx = Math.cos(-0.12),
    sx = Math.sin(-0.12),
    thickness = 18;
  const rx = x * cy + z * thickness * sy;
  const rz = -x * sy + z * thickness * cy;
  const ry = y * cx - rz * sx;
  const zz = y * sx + rz * cx;
  const perspective = 340 / (340 + zz);
  const px = Math.round(cols / 2 + rx * perspective * 0.79),
    py = Math.round(rows / 2 + ry * perspective * 0.395);
  if (px < 0 || px >= cols || py < 0 || py >= rows) return;
  const index = py * cols + px;
  if (zz >= buffer[index]) return;
  buffer[index] = zz;
  chars[index] = shadePoint(point, cy, sy);
}

function shadePoint([, , , nx, ny, nz]: Point, cy: number, sy: number) {
  const cx = Math.cos(-0.12),
    sx = Math.sin(-0.12);
  const normalX = nx * cy + nz * sy;
  const normalZ = -nx * sy + nz * cy;
  const normalY = ny * cx - normalZ * sx;
  const facingZ = ny * sx + normalZ * cx;
  const light = Math.max(0, normalX * -0.35 + normalY * -0.45 - facingZ * 0.82);
  const shade = Math.min(1, 0.27 + light * 0.73);
  return ramp[Math.floor(shade * (ramp.length - 1))];
}

const points = createPoints();

export function createAsciiRenderer() {
  const buffer = new Float32Array(cols * rows);
  const chars: string[] = new Array(cols * rows);
  return (yaw: number) => {
    buffer.fill(Infinity);
    chars.fill(' ');
    const frame = { cy: Math.cos(yaw), sy: Math.sin(yaw), buffer, chars };
    for (const point of points) projectPoint(point, frame);
    const lines = [];
    for (let y = 0; y < rows; y++) lines.push(chars.slice(y * cols, (y + 1) * cols).join(''));
    return lines.join('\n');
  };
}
