/* eslint-env node */
/* global process */

import { randomUUID } from 'node:crypto';
import htmlMinify from 'html-minifier-next';
import { parse, parseFragment } from 'parse5';
import { replaceTextRanges } from '../utils/string.js';

const IS_FULL_HTML_DOCUMENT = /<!doctype|<html[\s>]/i;

function isHtmlOutput(outputPath, content) {
  if (outputPath) return outputPath.endsWith('.html');

  return IS_FULL_HTML_DOCUMENT.test(content);
}

export async function htmlMinifyTransform(content, outputPath) {
  if (!isHtmlOutput(outputPath ?? this.page?.outputPath, content)) return content;

  let result = '';
  try {
    result = process.env.ELEVENTY_RUN_MODE !== 'watch' ? await minifyHTML(content) : content;
  } catch (_) {
    result = content;
  }
  return result;
}

async function minifyHTML(html) {
  // Store raw contents with unique markers so the HTML minifier cannot reinterpret them.
  const protectedContents = [];
  const markerPrefix = `__HTML_MINIFY_${randomUUID().replaceAll('-', '')}_`;

  function protectContent(content) {
    const marker = `${markerPrefix}${protectedContents.length}__`;
    protectedContents.push(content);
    return marker;
  }

  const replacements = findVerbatimContentRanges(html).map(({ start, end }) => ({
    start,
    end,
    value: protectContent(html.slice(start, end))
  }));
  const htmlWithMarkers = replaceTextRanges(html, replacements);

  // Minify the HTML
  const minifiedHtml = await htmlMinify.minify(htmlWithMarkers, {
    includeAutoGeneratedTags: true,
    removeAttributeQuotes: true,
    removeComments: true,
    removeRedundantAttributes: true,
    removeScriptTypeAttributes: true,
    removeStyleLinkTypeAttributes: true,
    sortClassName: true,
    useShortDoctype: true,
    collapseWhitespace: true,
    conservativeCollapse: true,
    minifyCSS: true
  });

  // Restore protected contents
  return minifiedHtml.replace(new RegExp(`${markerPrefix}(\\d+)__`, 'g'), (match, index) => {
    return protectedContents[Number(index)] ?? match;
  });
}

// Keep complete outer contents unchanged through minification; nested ranges would overlap.
function findVerbatimContentRanges(html) {
  const ranges = [];
  const options = { sourceCodeLocationInfo: true };
  const document = IS_FULL_HTML_DOCUMENT.test(html) ? parse(html, options) : parseFragment(html, options);

  function visit(node) {
    const isJsonLd =
      node.tagName === 'script' &&
      node.attrs.some(
        attribute => attribute.name === 'type' && attribute.value.trim().toLowerCase() === 'application/ld+json'
      );
    if (node.tagName === 'template' || node.tagName === 'textarea' || isJsonLd) {
      const location = node.sourceCodeLocation;
      if (location?.startTag && location?.endTag) {
        ranges.push({ start: location.startTag.endOffset, end: location.endTag.startOffset });
      }
      return;
    }
    for (const child of node.childNodes ?? []) visit(child);
  }

  visit(document);
  return ranges;
}
