const resizeKeys: readonly string[] = [
  'ArrowLeft',
  'ArrowRight',
  'ArrowUp',
  'ArrowDown',
  'Home',
  'End',
  'PageUp',
  'PageDown'
];

export function isResizeKey(key: string): boolean {
  return resizeKeys.includes(key);
}
